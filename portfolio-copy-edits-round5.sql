## Applied is where identity either survives or falls apart

A mark that reads perfectly on a screen can disappear when it is embroidered, stretched across a shoulder seam, printed on a curved surface, or reproduced in a single thread colour by a supplier who has never seen the guidelines. Application is the stress test, and a surprising amount of otherwise good identity work fails it.

## Embroidery removes the things you were relying on

Fine lines fill in. Gradients are not available. Small text turns into texture. Anything below a certain stroke weight simply does not exist once it is thread. A system that has not planned for this ends up with a special one-off version of the logo for shirts, which is the precise moment a brand starts fragmenting.

The fix is upstream: design a mark that already has a reduced form, and specify it, rather than improvising one under deadline pressure at a supplier.

## Uniform is the hardest case

It is worn by people who did not choose it, in front of customers, all day. It has to survive washing, it has to work across body shapes and garment colours, and it has to be something staff are not embarrassed to be seen in. That last requirement is a design constraint even though it never appears in a brief.

## Why this is one entry rather than several

These are pieces of applied work across different clients rather than a single engagement, grouped because what they demonstrate is the same thing: what happens to identity after handover.

## What the role actually was
This was the applied end of identity work: taking marks that already existed, mine and other people's, and making them survive contact with manufacture.

That is a different job from designing a logo and it is mostly diagnosis. Before anything is sent, the questions are what the production method removes, what the substrate does to colour, and what the smallest instance will be. Embroidery removes fine detail and tight counters. Screen printing on dark fabric changes what a colour is. A uniform is seen in motion, at distance, mostly from behind.

