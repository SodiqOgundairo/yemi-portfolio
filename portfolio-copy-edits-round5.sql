## Print does not forgive

A screen is a forgiving medium. It is backlit, it is a known size, the colour space is predictable, and a mistake is a redeploy away from being fixed. Print is none of those things. Ink behaves differently on different stock, a colour that sang on a monitor can go muddy on uncoated paper, and a misjudged margin becomes ten thousand copies of a misjudged margin.

Designing for it teaches a kind of care that transfers directly to everything else. If you have had to specify bleed and trim on something irreversible, you stop being casual about spacing on a screen.

## A book cover is a single-frame argument

It has one job, performed at thumbnail size in a list, in a fraction of a second, against competitors doing the same thing. There is no scroll, no second screen, no progressive disclosure. Every decision about type weight, image crop and contrast is made against that one exposure.

It is the purest exercise in hierarchy available, and it is why cover work is worth keeping in a portfolio that is otherwise about software.

## Mockups are part of the deliverable, not decoration

Taking cover art through to a finished mockup is what lets a client see the object rather than the file. A flat JPEG asks someone to imagine a physical thing; a mockup removes the imagination step, and the number of revision rounds usually drops because of it.

## Working method
Print work is planned backwards from the constraint, because the constraint is fixed and arrives last.

The sequence is stock and process first, then the design, then the proof. Uncoated paper takes ink differently from coated and a colour chosen on a screen is a guess until it is seen on the sheet it will live on. Trim, bleed and the way a cover wraps a spine are decided before the artwork is finished, not after, because a spine width depends on a page count somebody else controls.

The mockups are part of the same discipline rather than presentation polish. Showing a cover in the hand answers the only question that matters about it, whether it survives being small, at an angle, next to competitors, which is how every book is actually encountered.
